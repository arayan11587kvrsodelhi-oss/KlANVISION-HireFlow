"""SQLAlchemy model for the ``resumes`` table.

Resumes are stored as files in S3 storage. This table only tracks metadata
about the resume (filename, storage location, owner). The actual file content
never passes through the database — it uses S3 presigned URLs for secure
file delivery.

``resumes`` is linked to ``users`` (candidate) via ``owner_id`` and can
also be referenced from ``candidate_profiles`` and ``applications``.
"""

from sqlalchemy import (
    Column,
    String,
    Integer,
    ForeignKey,
    DateTime,
)
from sqlalchemy.orm import relationship

from ..db.base import Base


class Resume(Base):
    """Resume metadata for a candidate.

    Resumes are stored in S3 bucket via presigned URLs. The actual file is
    never stored as base64 in the database or exposed via public paths.

    Access is controlled through time-limited signed URLs generated by the
    backend, ensuring secure file delivery.
    """

    __tablename__ = "resumes"

    id = Column(
        String(36),
        primary_key=True,
        unique=True,
        index=True,
        nullable=False,
    )

    owner_id = Column(
        String(36),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )

    filename = Column(
        String(255),
        nullable=False,
    )  # Original filename (e.g., "john-resume.pdf")

    s3_key = Column(
        String(500),
        nullable=False,
    )  # S3 object key (unique within bucket)

    mimetype = Column(
        String(100),
        nullable=True,
    )  # e.g., "application/pdf"

    size_bytes = Column(
        Integer,
        nullable=True,
    )  # File size in bytes

    uploaded_at = Column(
        DateTime, server_default="now()", nullable=False
    )

    status = Column(
        String(20),
        nullable=False,
        default="active",
    )  # active, inactive, processing

    # Relationships
    owner = relationship("User", back_populates="resumes")

    application = relationship("Application", back_populates="resume", uselist=False)